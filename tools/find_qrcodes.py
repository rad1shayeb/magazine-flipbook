#!/usr/bin/env python3
"""Find QR codes in the source page exports and write hotspots to js/links.js.

Detection runs on the full-resolution source images (A3 pages are split into
A4 leaves exactly like build_pages.py) because small QR codes can be missed in
the 150 dpi page images. Coordinates are stored normalised (0..1) relative to
each leaf, so they map directly onto img/pages/pNN.jpg.

Usage:
    python3 tools/find_qrcodes.py [source-dir]

Default source dir: ~/Downloads/flipbook
Requires: pip install opencv-python-headless pillow
"""

import glob
import json
import os
import re
import sys

import cv2
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "js", "links.js")


def sort_key(path):
    stem = os.path.basename(path).rsplit(".", 1)[0]
    nums = re.findall(r"\d+", stem)
    return int(nums[-1]) if nums else 0


def box_from_points(pts, w, h):
    pts = np.asarray(pts, dtype=float).reshape(-1, 2)
    x0, y0 = pts.min(axis=0)
    x1, y1 = pts.max(axis=0)
    return (
        max(0.0, x0) / w,
        max(0.0, y0) / h,
        min(1.0, (x1 - x0) / w),
        min(1.0, (y1 - y0) / h),
    )


def overlaps(a, b, iou_min=0.25):
    ax, ay, aw, ah = a
    bx, by, bw, bh = b
    ix = max(0.0, min(ax + aw, bx + bw) - max(ax, bx))
    iy = max(0.0, min(ay + ah, by + bh) - max(ay, by))
    inter = ix * iy
    if inter <= 0:
        return False
    smaller = min(aw * ah, bw * bh)
    return smaller > 0 and inter / smaller > iou_min


def detect_array(img_bgr):
    h, w = img_bgr.shape[:2]
    found = []
    det = cv2.QRCodeDetector()

    try:
        ok, texts, pts, _ = det.detectAndDecodeMulti(img_bgr)
        if ok and pts is not None:
            for text, p in zip(texts, pts):
                if text:
                    found.append((text, box_from_points(p, w, h)))
    except cv2.error:
        pass

    # Sequential pass with masking catches codes the multi detector missed.
    work = img_bgr.copy()
    for _ in range(8):
        try:
            text, pts, _ = det.detectAndDecode(work)
        except cv2.error:
            break
        if not text or pts is None:
            break
        box = box_from_points(pts, w, h)
        if not any(overlaps(box, b) for _, b in found):
            found.append((text, box))
        x = max(0, int(box[0] * w) - 8)
        y = max(0, int(box[1] * h) - 8)
        x2 = min(w - 1, int((box[0] + box[2]) * w) + 8)
        y2 = min(h - 1, int((box[1] + box[3]) * h) + 8)
        cv2.rectangle(work, (x, y), (x2, y2), (0, 0, 0), -1)

    try:
        import zxingcpp

        for r in zxingcpp.read_barcodes(Image.fromarray(cv2.cvtColor(img_bgr, cv2.COLOR_BGR2RGB))):
            box = (r.position.top_left.x / w, r.position.top_left.y / h,
                   (r.position.top_right.x - r.position.top_left.x) / w,
                   (r.position.bottom_left.y - r.position.top_left.y) / h)
            if r.text and not any(overlaps(box, b) for _, b in found):
                found.append((r.text, box))
    except Exception:
        pass

    found.sort(key=lambda f: (f[1][1], f[1][0]))
    return found


def leaf_images(src_dir):
    files = []
    for ext in ("*.png", "*.jpg", "*.jpeg"):
        files.extend(glob.glob(os.path.join(src_dir, ext)))
    files.sort(key=sort_key)
    for path in files:
        im = Image.open(path).convert("RGB")
        w, h = im.size
        if w > h * 1.02:
            mid = w // 2
            yield path, im.crop((0, 0, mid, h))
            yield path, im.crop((mid, 0, w, h))
        else:
            yield path, im


def main():
    src_dir = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/Downloads/flipbook")
    leaves = list(leaf_images(src_dir))
    if not leaves:
        raise SystemExit("No page images found in %s" % src_dir)

    links = {}
    total = 0
    for i, (src, leaf) in enumerate(leaves, 1):
        name = "p%02d.jpg" % i
        rel = "img/pages/" + name
        arr = cv2.cvtColor(np.array(leaf), cv2.COLOR_RGB2BGR)
        hits = detect_array(arr)
        if hits:
            links[rel] = [
                {
                    "x": round(x, 5),
                    "y": round(y, 5),
                    "w": round(bw, 5),
                    "h": round(bh, 5),
                    "url": url,
                }
                for url, (x, y, bw, bh) in hits
            ]
            total += len(hits)
        print("%-14s %d QR code(s)" % (name, len(hits)))
        for url, _ in hits:
            print("    -> %s" % url)

    with open(OUT, "w") as fh:
        fh.write("// Generated by tools/find_qrcodes.py — do not edit by hand.\n")
        fh.write("// Source: %s\n" % src_dir)
        fh.write("window.MAGAZINE_LINKS = ")
        fh.write(json.dumps(links, indent=2, ensure_ascii=False))
        fh.write(";\n")

    print("total: %d QR code(s) -> js/links.js" % total)


if __name__ == "__main__":
    main()
