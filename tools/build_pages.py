#!/usr/bin/env python3
"""Build A4 leaf images for the flipbook from exported page PNGs.

Usage:
    python3 tools/build_pages.py [source-dir]

Default source dir: ~/Downloads/flipbook

- A4 pages (portrait) become one leaf each.
- A3 pages (landscape) are split down the middle into left/right A4 leaves.
- Everything is resized to 1240x1754 (A4 @ 150 dpi) and saved as JPEG
  into img/pages/pNN.jpg.
- Regenerates img/cover.png (social share image) and js/pages.js manifest.
"""

import glob
import os
import re
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/Downloads/flipbook")
OUT_DIR = os.path.join(ROOT, "img", "pages")
MANIFEST = os.path.join(ROOT, "js", "pages.js")
COVER = os.path.join(ROOT, "img", "cover.png")

W, H = 1240, 1754  # A4 @ 150 dpi


def sort_key(path):
    stem = os.path.basename(path).rsplit(".", 1)[0]
    nums = re.findall(r"\d+", stem)
    return int(nums[-1]) if nums else 0


def main():
    files = []
    for ext in ("*.png", "*.jpg", "*.jpeg"):
        files.extend(glob.glob(os.path.join(SRC, ext)))
    files.sort(key=sort_key)
    if not files:
        sys.exit("No page images found in %s" % SRC)

    os.makedirs(OUT_DIR, exist_ok=True)
    for old in glob.glob(os.path.join(OUT_DIR, "*")):
        os.remove(old)

    leaves = []
    for path in files:
        im = Image.open(path).convert("RGB")
        w, h = im.size
        if w > h * 1.02:  # A3 landscape spread -> two A4 leaves
            mid = w // 2
            leaves.append(im.crop((0, 0, mid, h)))
            leaves.append(im.crop((mid, 0, w, h)))
        else:
            leaves.append(im)

    paths = []
    total = 0
    for i, leaf in enumerate(leaves, 1):
        name = "p%02d.jpg" % i
        out = os.path.join(OUT_DIR, name)
        leaf.resize((W, H), Image.LANCZOS).save(
            out, "JPEG", quality=90, optimize=True, progressive=True
        )
        paths.append("img/pages/" + name)
        total += os.path.getsize(out)
        print("%-12s %6.0f KB" % (name, os.path.getsize(out) / 1024))

    leaves[0].resize((1000, 1414), Image.LANCZOS).save(COVER, "PNG", optimize=True)

    with open(MANIFEST, "w") as fh:
        fh.write("// Generated by tools/build_pages.py — do not edit by hand.\n")
        fh.write("// Source: %s\n" % SRC)
        fh.write("window.MAGAZINE_PAGES = [\n")
        for p in paths:
            fh.write('  "%s",\n' % p)
        fh.write("];\n")

    print(
        "pages: %d leaves from %d files, %.2f MB total"
        % (len(paths), len(files), total / 1e6)
    )


if __name__ == "__main__":
    main()
